#!/usr/bin/env python3
# XPSemu: the LaunchBox Games Database's box art of Xbox games (fronts from outside North America, backs and spines from every region), as
# ui/launchbox-box-index.h: each game's names (its own and alternates) with each region's "Box - Front"
# picture, so a European or Japanese disc gets its own region's cover (patch 315). Files are at
# https://images.launchbox-app.com/<file>.
#
# Usage: ps5/make-launchbox-box-index.py Metadata.zip   (https://gamesdb.launchbox-app.com/Metadata.zip)
import collections
import os
import sys
import zipfile
import xml.etree.ElementTree as ET

here = os.path.dirname(os.path.abspath(__file__))
z = zipfile.ZipFile(sys.argv[1])
games, alts, boxes = {}, collections.defaultdict(list), collections.defaultdict(dict)
SKIP = {'', 'north america', 'united states', 'canada', 'world'}
KINDS = {'Box - Front': 'F', 'Box - Back': 'B', 'Box - Spine': 'S'}


def text(el, tag):
    return (el.findtext(tag) or '').strip()


for _, el in ET.iterparse(z.open('Metadata.xml')):
    if el.tag == 'Game':
        if text(el, 'Platform') == 'Microsoft Xbox':
            games[text(el, 'DatabaseID')] = text(el, 'Name')
        el.clear()
    elif el.tag == 'GameAlternateName':
        alts[text(el, 'DatabaseID')].append(text(el, 'AlternateName'))
        el.clear()
    elif el.tag == 'GameImage':
        region = text(el, 'Region')
        kind = KINDS.get(text(el, 'Type'))
        # fronts from outside North America (xdb has the American ones); backs and spines from everywhere
        if kind and (kind != 'F' or region.lower() not in SKIP):
            boxes[text(el, 'DatabaseID')].setdefault((kind, region), text(el, 'FileName'))
        el.clear()

rows = set()
for gid, name in games.items():
    for (kind, region), file in boxes.get(gid, {}).items():
        for n in [name] + alts.get(gid, []):
            if n:
                rows.add((n, kind, region, file))


def c(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


out = os.path.join(here, 'ui', 'launchbox-box-index.h')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by ps5/make-launchbox-box-index.py: do not edit.\n#pragma once\n\n')
    f.write('// LaunchBox Games Database, Microsoft Xbox: box art by game name, kind and region\n')
    f.write('// (images.launchbox-app.com/<file>), patch 315. kind: F front (outside North America only),\n')
    f.write('// B back, S spine (every region).\n')
    f.write('static const struct { const char *name; char kind; const char *region, *file; } kLaunchboxXboxBox[] = {\n')
    for n, k, r, fl in sorted(rows):
        f.write("    { %s, '%s', %s, %s },\n" % (c(n), k, c(r), c(fl)))
    f.write('};\n')
print(len(rows), 'rows,', len(boxes), 'games with region boxes ->', out)
