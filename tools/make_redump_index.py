#!/usr/bin/env python3
# XPSemu: ps5/ui/redump-index.h from libretro-database's Redump Xbox list
# (metadat/redump/Microsoft - Xbox.dat, CC BY-SA 4.0, libretro and Redump): each disc's title ID
# (from its serial: "EA-013" is publisher EA, game 13, title ID 4541000D), Redump name, region,
# languages and revision. The generated table stays CC BY-SA 4.0 (licenses/libretro-database.txt).
# Our own code. GPL-3.0-or-later.
import re
import sys

LANG = re.compile(r"^(?:[A-Z][a-z](?:-[A-Z][a-z]+)?)(?:,[A-Z][a-z](?:-[A-Z][a-z]+)?)*$")


def title_id(serial):
    m = re.match(r"^([A-Z0-9]{2})-(\d{1,5})", serial.strip())
    if not m:
        return None
    num = int(m.group(2))
    if num > 0xFFFF:
        return None
    a, b = m.group(1)
    return (ord(a) << 24) | (ord(b) << 16) | num


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(src, dst):
    text = open(src, encoding="utf-8", errors="replace").read()
    rows = []
    for block in re.findall(r'^game \((.*?)^\)', text, re.S | re.M):
        name = re.search(r'^\s*name "([^"]*)"', block, re.M)
        region = re.search(r'^\s*region "([^"]*)"', block, re.M)
        serial = re.search(r'^\s*serial "([^"]*)"', block, re.M)
        if not (name and serial):
            continue
        name = name.group(1)
        groups = re.findall(r"\(([^)]*)\)", name)
        langs = next((g for g in groups if LANG.match(g)), "")
        rev = next((g for g in groups if g.startswith("Rev ") or g.startswith("v")), "")
        ids = {title_id(s) for s in serial.group(1).split(",")}
        for tid in sorted(i for i in ids if i):
            rows.append((tid, name, region.group(1) if region else "", langs, rev))
    rows.sort()
    with open(dst, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/make_redump_index.py from libretro-database's Redump Xbox list\n")
        out.write("// (CC BY-SA 4.0, libretro and Redump). Don't edit: run the tool again.\n")
        out.write("struct RedumpDisc { uint32_t title_id; const char *name, *region, *languages, *revision; };\n")
        out.write("static const RedumpDisc kRedumpDiscs[] = {\n")
        for tid, name, region, langs, rev in rows:
            out.write("    { 0x%08X, %s, %s, %s, %s },\n" % (tid, c(name), c(region), c(langs), c(rev)))
        out.write("};\n")
    print("%d discs, %d title IDs -> %s" % (len(rows), len({r[0] for r in rows}), dst))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
