"""Generate native/kernel/kexports_table.h from native/kernel/xboxkrnl.exe.def.

The .def (nxdk, CC0-1.0) lists every xboxkrnl export with its ordinal and
MSVC decoration, which gives the calling convention and argument bytes:
  Name@N      stdcall, N bytes of stack arguments
  @Name@N     fastcall, first two dwords in ECX/EDX, the rest on the stack
  Name        cdecl (caller cleans the stack)
  Name DATA   a variable, not a function

Usage: python gen_kexports.py native/kernel/xboxkrnl.exe.def native/kernel/kexports_table.h
"""

import re
import sys

LINE = re.compile(r"^\s*(@?)([A-Za-z_][A-Za-z0-9_]*)(?:@(\d+))?\s+@\s*(\d+)\s+NONAME(\s+DATA)?\s*$")


def main():
    src, dst = sys.argv[1], sys.argv[2]
    rows = []
    with open(src, encoding="utf-8") as f:
        for line in f:
            m = LINE.match(line)
            if not m:
                continue
            fast, name, nbytes, ordinal, data = m.groups()
            if data:
                abi = "NC_KABI_DATA"
            elif fast:
                abi = "NC_KABI_FASTCALL"
            elif nbytes is not None:
                abi = "NC_KABI_STDCALL"
            else:
                abi = "NC_KABI_CDECL"
            rows.append((int(ordinal), name, abi, int(nbytes or 0)))
    rows.sort()
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/native/gen_kexports.py from xboxkrnl.exe.def\n")
        f.write(" * (nxdk, CC0-1.0). Do not edit. */\n")
        f.write("/* { ordinal, name, abi, stack argument bytes } */\n")
        for ordinal, name, abi, nbytes in rows:
            f.write('NC_KEXPORT(%d, "%s", %s, %d)\n' % (ordinal, name, abi, nbytes))
    print("%d exports, highest ordinal %d" % (len(rows), rows[-1][0]))


if __name__ == "__main__":
    main()
