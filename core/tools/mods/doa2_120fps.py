"""doa2_120fps.py XBE [OUT]: Dead or Alive 2 Ultimate's 120 fps mod
(mods/54430006.6/120fps/mod.txt) from its doa2.xbe: the header, then the
XBE patches, the injected code assembled here (to OUT, else stdout).

The vblank runs at 120 Hz (refresh: 120). The code goes in the header page
past the headers (sizeof_headers 0xC68 -> 0x1000: the loader reads the
page's rest from the file, zeros there):

- A logic frame is the first main-loop pass of each 60 Hz tick (D3D's
  vblank count, at 120 Hz, halved), checked at the main loop's controller
  update (the call at 0xFF3AF): only logic frames read the controllers, so
  a press's "just pressed" lasts the logic frame every task sees. PARITY is
  0 on logic frames.
- D3D's draws (DrawIndexedVertices, DrawVertices, DrawVerticesUP) set the
  current task slot's bit in DRAWN; CreateTask clears the slot's bit. On
  the other frames the scheduler (its slot check at 0xFA467) skips the tasks
  that never drew: the logic keeps 60 updates a second, the tasks that draw
  run every frame.

Where the work stands and what is next: HANDOFF.md, "DOA2 120 fps mod".
"""
import struct
import sys

d = open(sys.argv[1], 'rb').read()
base = struct.unpack_from('<I', d, 0x104)[0]
hdr = struct.unpack_from('<I', d, 0x108)[0]
nsec, secva = struct.unpack_from('<II', d, 0x11C)
first_raw = min(struct.unpack_from('<I', d, secva - base + i * 0x38 + 0xC)[0] for i in range(nsec))
assert hdr == 0xC68 and first_raw >= 0x1000, (hex(hdr), hex(first_raw))
assert not any(d[hdr:0x1000]), 'the header page past the headers is not empty in the file'

HEADER = """name: 120 fps (in progress)
description: The game at 120 frames a second (on a 120 Hz screen), at its normal speed. In progress: each logic frame is shown twice (no blending yet).
author: hakuX
refresh: 120

# doa2.xbe runs its game as fiber tasks (24 slots at 0xA94570, scheduler
# 0xFA440). With the vblank at 120 Hz the main loop runs every vblank; the
# first pass of each 60 Hz tick (D3D's vblank count halved, checked at its
# controller update 0xFF3AF) is a logic frame; on the other frames
# the controllers aren't read and the scheduler skips the tasks that never
# drew: the logic keeps 60 updates a second, the tasks that draw run every
# frame, and so do the select screen's model loader (0x12F490, 0x12F460:
# skipped, its fighters were drawn every other tick) and the fight's render
# setup (0x116B20: skipped, the frames in between drew with the last
# frame's render state and draw lists, the ground under the fighters
# darker every other tick). The game's frame counter (0x87D56C) and the
# render setup's (0x850730) move on logic frames only (the menus' loop
# draws and runs every frame). A logic frame's 2D lists (text, icons:
# appended at 0xB0590, drawn by the 2D task 0x6D0B0) stay until the next
# logic frame's start, and the frames in between drop their appends: the
# select screen's "A Select / B Back", appended by a task that doesn't draw,
# was missing every other frame. The code is in the header page
# (sizeof_headers raised to 0x1000): the draws mark the current slot in a
# bitmap at 0x10CF0, CreateTask clears it. Generated by
# tools/mods/doa2_120fps.py.
[doa2.xbe]
"""


def file_bytes(va, n):
    """the XBE's bytes at a VA (sections' raw data, or the header page)"""
    for i in range(nsec):
        flags, sva, vsize, raw, rsize = struct.unpack_from('<IIIII', d, secva - base + i * 0x38)
        if sva <= va < sva + rsize:
            o = raw + va - sva
            return d[o:o + n]
    if base <= va < base + 0x1000:
        return d[va - base:va - base + n]
    raise ValueError(hex(va))


def hx(b):
    return ' '.join('%02X' % x for x in b)


class Asm:
    def __init__(self, at):
        self.at, self.b = at, bytearray()

    def pc(self):
        return self.at + len(self.b)

    def raw(self, *bs):
        self.b += bytes(bs)

    def u32(self, v):
        self.b += struct.pack('<I', v & 0xFFFFFFFF)

    def rel32(self, op, target):          # E8 / E9 rel32
        self.raw(op)
        self.u32(target - (self.pc() + 4))

    def jcc32(self, op, target):          # 0F 8x rel32
        self.raw(0x0F, op)
        self.u32(target - (self.pc() + 4))

    def done(self):
        return self.at, bytes(self.b)


# The title's addresses
SLOT = 0xA94814          # the current task's slot (-1: the main fiber)
INPUT = 0xFAC20          # the controllers' update, called by the main loop at 0xFF3AF
SKIP, RUN = 0xFA4A8, 0xFA46C     # the scheduler's slot loop: next slot, resume this one
DEVICE = 0x3554F8        # D3D's device; its vblank count at +0x1DE8 (GetDisplayFieldStatus)
CREATE = 0xFA570         # CreateTask(slot, entry): push esi / mov esi, [esp+8]
DRAWS = ((0x348450, 6), (0x3483B0, 7), (0x348240, 6))   # D3D draws: entry, whole instructions moved
COUNTER = 0x87D56C       # the game's frame counter (bumped at 0xD9364 and 0xDAF32)

# The mod's variables and code in the header page
DRAWN = 0x10CF0          # the slots that drew (a bit each)
PARITY = 0x10CF4         # 0 on logic frames
LASTTICK = 0x10CF8       # the tick of the last logic frame
C_INPUT, C_DRAW, C_CREATE, C_SCHED, C_COUNT = 0x10D00, 0x10D40, 0x10DA0, 0x10DC0, 0x10DF0
C_ALWAYS, C_TICK = 0x10E20, 0x10E80
ALWAYS = (0x12F490, 0x12F460, 0x116B20)   # task entries run on every frame (they don't draw)
TICK = 0x850730          # the render task's frame count (0x5C460 bumps it; a fighter drawn twice in one draws a repeat)
PENDING = 0x10E90        # the 2D lists' reset, put off at a logic frame's end
C_RESET, C_APPEND, C_LOGIC = 0x10EA0, 0x10ED0, 0x10EF0
APPEND = 0xB0590         # the 2D lists' append (item, layer): its node from 0x8A0178, its layer's tail at 0x8A0940
RESET = 0xAE300          # their reset (the lists, the node and vertex scratch, 0x8A0754): the 2D task's (slot 15)
RESET_CALLS = (0x6D124, 0x6D130)   # ... at its frame's end, after its walk (0xB0600) drew them

blocks = []

# The main loop's controller update: a logic frame reads the controllers
ip = Asm(C_INPUT)
ip.raw(0xA1); ip.u32(DEVICE)                      # mov eax, [DEVICE]
ip.raw(0x8B, 0x80); ip.u32(0x1DE8)                # mov eax, [eax+0x1DE8]
ip.raw(0xD1, 0xE8)                                # shr eax, 1
ip.raw(0x3B, 0x05); ip.u32(LASTTICK)              # cmp eax, [LASTTICK]
ip.raw(0x74, 0x14)                                # je other (20 bytes below)
ip.raw(0xA3); ip.u32(LASTTICK)                    # mov [LASTTICK], eax
ip.raw(0xC7, 0x05); ip.u32(PARITY); ip.u32(0)     # mov dword [PARITY], 0
ip.rel32(0xE9, C_LOGIC)                           # jmp C_LOGIC, then INPUT (its ret returns to the main loop)
ip.raw(0xC7, 0x05); ip.u32(PARITY); ip.u32(1)     # other: mov dword [PARITY], 1
ip.raw(0xC3)                                      # ret
assert ip.b[19:21] == b'\x74\x14' and ip.b[21 + 0x14:21 + 0x16] == b'\xC7\x05' and ip.b[-1] == 0xC3
blocks.append(ip.done())
j = Asm(0xFF3AF)
assert file_bytes(0xFF3AF, 5) == b'\xE8' + struct.pack('<i', INPUT - 0xFF3B4)
j.rel32(0xE8, C_INPUT)                            # call the cave instead of INPUT
blocks.append(j.done())

# The scheduler's slot check (test cl, 2 / jne SKIP): on the other frames a
# task that never drew is skipped too (its wait untouched)
assert file_bytes(0xFA467, 5) == bytes.fromhex('f6c102753c') and 0xFA46C + 0x3C == SKIP
sc = Asm(C_SCHED)
sc.raw(0xF6, 0xC1, 0x02)                          # test cl, 2 (paused)
sc.jcc32(0x85, SKIP)                              # jne SKIP
sc.raw(0x83, 0x3D); sc.u32(PARITY); sc.raw(0x00)  # cmp dword [PARITY], 0
sc.jcc32(0x84, RUN)                               # je RUN: a logic frame
sc.raw(0x50)                                      # push eax
sc.raw(0xA1); sc.u32(SLOT)                        # mov eax, [SLOT] (the slot the loop is at)
sc.raw(0x0F, 0xA3, 0x05); sc.u32(DRAWN)           # bt [DRAWN], eax
sc.raw(0x58)                                      # pop eax (flags kept)
sc.jcc32(0x82, RUN)                               # jc RUN: a task that draws
sc.rel32(0xE9, C_ALWAYS)                          # jmp C_ALWAYS
blocks.append(sc.done())
# Tasks that run every frame without drawing: the select screen's fighters
# load through a service (0x12F490, fed by 0x12F460) whose requests the
# frames in between leave half done: the fighters were drawn every other tick.
# The fight's render task (0x116B20) starts each frame: it resets D3D's
# render state and the draw lists, sets the lights and queues the fighters'
# shadows; skipped, the frames in between drew with the last frame's state
# and lists, the ground under the fighters darker every other tick
al = Asm(C_ALWAYS)
for entry in ALWAYS:
    al.raw(0x81, 0x7E, 0x0C); al.u32(entry)       # cmp dword [esi+0xC], entry (the slot's task)
    al.jcc32(0x84, RUN)                           # je RUN
al.rel32(0xE9, SKIP)                              # jmp SKIP
assert C_ALWAYS + len(al.b) <= C_TICK
blocks.append(al.done())
j = Asm(0xFA467)
j.rel32(0xE9, C_SCHED)
blocks.append(j.done())

# The draws mark the current slot: each entry's first instructions move to
# a cave after the marking; the entry jumps there
for k, (entry, nreloc) in enumerate(DRAWS):
    cave = C_DRAW + 0x20 * k
    a = Asm(cave)
    a.raw(0x50)                                   # push eax
    a.raw(0xA1); a.u32(SLOT)                      # mov eax, [SLOT]
    a.raw(0x83, 0xF8, 24)                         # cmp eax, 24
    a.raw(0x73, 0x07)                             # jae skip (the bts is 7 bytes)
    a.raw(0x0F, 0xAB, 0x05); a.u32(DRAWN)         # bts [DRAWN], eax
    a.raw(0x58)                                   # skip: pop eax
    a.b += file_bytes(entry, nreloc)
    a.rel32(0xE9, entry + nreloc)                 # jmp back
    assert len(a.b) <= 0x20
    blocks.append(a.done())
    e = Asm(entry)
    e.rel32(0xE9, cave)
    e.b += b'\x90' * (nreloc - 5)
    blocks.append(e.done())

# The game's frame counter (0x87D56C: draw requests stamp it, a task that
# finds it unmoved repeats its last frame) counts logic frames only. Its two
# loops bump it after their one-frame wait; the menus' loop (0xDAF24) draws,
# so it runs on the other frames too, and the counter went at 120 a second:
# the select screen's fighters were drawn every other tick.
for k, (at, reg, inc_at) in enumerate(((0xD935B, 2, 0xD9364), (0xDAF24, 1, 0xDAF32))):
    load = bytes((0x8B, 0x05 | reg << 3)) + struct.pack('<I', COUNTER)  # mov e?x, [COUNTER]
    assert file_bytes(at, 6) == load and file_bytes(inc_at, 1) == bytes((0x40 | reg,))
    cv = Asm(C_COUNT + 0x14 * k)
    cv.b += load
    cv.raw(0x83, 0x3D); cv.u32(PARITY); cv.raw(0x00)  # cmp dword [PARITY], 0
    cv.raw(0x75, 0x01)                            # jne ret: not a logic frame
    cv.raw(0x40 | reg)                            # inc e?x
    cv.raw(0xC3)                                  # ret
    assert len(cv.b) <= 0x14
    blocks.append(cv.done())
    j = Asm(at)
    j.rel32(0xE8, cv.at)                          # call the cave (the load, the bump)
    j.raw(0x90)
    blocks.append(j.done())
    j = Asm(inc_at)
    j.raw(0x90)                                   # its inc done there
    blocks.append(j.done())

# The render task's frame count moves on logic frames only: a fighter drawn
# again at the same count takes the game's repeat path (0x5B729), which
# leaves its animation phase (0x5D0E0, a step per count) alone
assert file_bytes(0x5C460, 1) == b'\xA1' and file_bytes(0x5C461, 4) == struct.pack('<I', TICK)
assert file_bytes(0x5C46C, 6) == bytes.fromhex('25ff7f000040')
tk = Asm(C_TICK)
tk.raw(0x25); tk.u32(0x7FFF)                      # and eax, 0x7FFF
tk.raw(0x83, 0x3D); tk.u32(PARITY); tk.raw(0x00)  # cmp dword [PARITY], 0
tk.raw(0x75, 0x01)                                # jne ret: not a logic frame
tk.raw(0x40)                                      # inc eax
tk.raw(0xC3)                                      # ret
blocks.append(tk.done())
j = Asm(0x5C46C)
j.rel32(0xE8, C_TICK)                             # call the cave (the mask, the bump)
j.raw(0x90)
blocks.append(j.done())

# CreateTask clears the new task's bit
assert file_bytes(CREATE, 5) == bytes.fromhex('568b742408')
ct = Asm(C_CREATE)
ct.raw(0x56)                                      # push esi
ct.raw(0x8B, 0x74, 0x24, 0x08)                    # mov esi, [esp+8]
ct.raw(0x0F, 0xB3, 0x35); ct.u32(DRAWN)           # btr [DRAWN], esi
ct.rel32(0xE9, CREATE + 5)                        # jmp back
blocks.append(ct.done())
j = Asm(CREATE)
j.rel32(0xE9, C_CREATE)
blocks.append(j.done())

# The 2D lists (layers 0-9 of items: text, icons, panels): tasks append to
# them during a frame, the 2D task (slot 15, every frame: it draws) draws
# them and resets them, with their node and vertex scratch. Tasks that don't
# draw append too, on logic frames only: the select screen's (slot 1,
# 0x13B800) puts up its "A Select / B Back" legend so, and it was missing
# every other frame. Now the lists a logic frame drew stay until the next
# logic frame's start (C_LOGIC resets them), and the frames in between drop
# their appends (APPEND's own answer when it is full, 0): they draw the
# logic frame's 2D again, like its 3D. A reset at the end of the frame in
# between left nothing for a third pass in one tick (a late vblank): the
# legend went out for a frame now and then.
rs = Asm(C_RESET)
rs.raw(0xC7, 0x05); rs.u32(PENDING); rs.u32(1)    # mov dword [PENDING], 1: put off
rs.raw(0xC3)                                      # ret
assert C_RESET + len(rs.b) <= C_APPEND
blocks.append(rs.done())
for at in RESET_CALLS:
    assert file_bytes(at, 5) == b'\xE8' + struct.pack('<i', RESET - (at + 5))
    j = Asm(at)
    j.rel32(0xE8, C_RESET)
    blocks.append(j.done())

assert file_bytes(APPEND, 5) == bytes.fromhex('a178018a00')   # mov eax, [0x8A0178]
ap = Asm(C_APPEND)
ap.raw(0x83, 0x3D); ap.u32(PARITY); ap.raw(0x00)  # cmp dword [PARITY], 0
ap.raw(0x74, 0x03)                                # je append: a logic frame
ap.raw(0x33, 0xC0)                                # xor eax, eax
ap.raw(0xC3)                                      # ret: dropped
ap.b += file_bytes(APPEND, 5)                     # append: mov eax, [0x8A0178]
ap.rel32(0xE9, APPEND + 5)                        # jmp back
assert C_APPEND + len(ap.b) <= C_LOGIC
blocks.append(ap.done())
j = Asm(APPEND)
j.rel32(0xE9, C_APPEND)
blocks.append(j.done())

lg = Asm(C_LOGIC)
lg.raw(0x83, 0x3D); lg.u32(PENDING); lg.raw(0x00) # cmp dword [PENDING], 0
lg.raw(0x74, 0x0F)                                # je input (15 bytes below)
lg.raw(0xC7, 0x05); lg.u32(PENDING); lg.u32(0)    # mov dword [PENDING], 0
lg.rel32(0xE8, RESET)                             # call RESET: the last logic frame's lists
lg.rel32(0xE9, INPUT)                             # input: jmp INPUT
assert lg.b[7:9] == b'\x74\x0F' and lg.b[9 + 0x0F] == 0xE9
assert C_LOGIC + len(lg.b) <= 0x11000
blocks.append(lg.done())

lines = ['0x%08X: %s -> %s' % (base + 0x108, hx(struct.pack('<I', hdr)), hx(struct.pack('<I', 0x1000)))]
for at, code in sorted(blocks, key=lambda b: (b[0] >= 0x11000, b[0] if b[0] < 0x11000 else 0)):
    lines.append('0x%08X: %s -> %s' % (at, hx(file_bytes(at, len(code))), hx(code)))
text = HEADER + '\n'.join(lines) + '\n'
if len(sys.argv) > 2:
    open(sys.argv[2], 'w', newline='\n').write(text)
else:
    sys.stdout.write(text)
