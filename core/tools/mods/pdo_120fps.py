# SetTransform: the view (0) and world (6-9) matrices of every frame are
# recorded in order, with the pointer they came from. The game sends each
# draw one matrix, the model's and the camera's together, from a slot of its
# matrix stack: nothing names the object, and how many draws the level takes
# changes as the camera moves. So a tick frame (a step past the one the
# frame before showed) looks for each matrix's match in the frame before's
# around the place the last match gave (the same index plus OFF, then
# +-1 .. +-WINDOW): the same state and slot, its translation within
# NEAR + FAR * distance and its rotation within TURN2 (squares). Found, the
# device gets the mean of the two (half a step back) and OFF follows; else,
# and on the other frames, the matrix goes as it is.
SSE = {'movups': (0x0F, 0x10), 'store': (0x0F, 0x11)}
SS = {'movss': 0x10, 'subss': 0x5C, 'mulss': 0x59, 'addss': 0x58}


def xmm_mem8(a, op, reg, base_reg, disp):        # op xmm, [base + disp8] (base: esi 6, eax 0)
    a.raw(*SSE[op], 0x40 | reg << 3 | base_reg, disp & 0xFF)


def xmm_abs(a, op, reg, addr):                   # op xmm, [addr] / op [addr], xmm
    a.raw(*SSE[op], reg << 3 | 5); a.u32(addr)


def ss_mem8(a, op, reg, base_reg, disp):         # movss / subss xmm, [base + disp8]
    a.raw(0xF3, 0x0F, SS[op], 0x40 | reg << 3 | base_reg, disp)


def ss_abs(a, op, reg, addr):                    # mulss / addss xmm, [addr]
    a.raw(0xF3, 0x0F, SS[op], reg << 3 | 5); a.u32(addr)


def xx(a, prefix, op, dst, src):                 # op xmm, xmm (prefix F3 for the scalar ones)
    a.raw(*prefix, 0x0F, op, 0xC0 | dst << 3 | src)


SUB, MUL, ADD, MOVAPS = 0x5C, 0x59, 0x58, 0x28
ESI, EAX = 6, 0
xf = Asm(C_XFORM)
xf.raw(0x8B, 0x44, 0x24, 0x04)                    # mov eax, [esp+4] (the state)
xf.raw(0x85, 0xC0)                                # test eax, eax
xf.j8(0x74, 'kept')                               # je kept (the view)
xf.raw(0x83, 0xF8, 0x06)                          # cmp eax, 6
xf.j32(0x72, 'orig')                              # jb orig
xf.raw(0x83, 0xF8, 0x09)                          # cmp eax, 9
