spans = sorted((at, at + len(code)) for at, code in blocks)
assert all(a[1] <= b[0] for a, b in zip(spans, spans[1:])), ['%x-%x' % s for s in spans]
assert spans[0][0] >= hdr + base and max(e for s, e in spans if s < 0x11000) <= 0x11000
lines = ['0x%08X: %s -> %s' % (base + 0x108, hx(struct.pack('<I', hdr)), hx(struct.pack('<I', 0x1000)))]
for at, code in sorted(blocks, key=lambda b: (b[0] >= 0x11000, b[0] if b[0] < 0x11000 else 0)):
    for k in range(0, len(code), 32):            # the app reads lines of 1023 characters at most
        part = code[k:k + 32]
        lines.append('0x%08X: %s -> %s' % (at + k, hx(file_bytes(at + k, len(part))), hx(part)))
text = HEADER + '\n'.join(lines) + '\n'
