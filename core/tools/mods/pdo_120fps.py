MAXREC, WINDOW = 2048, 8
REC, REC_M = 72, 8       # a record: the state, the pointer, the matrix (at REC_M)
CONSTANTS = ((NEAR, struct.pack('<fff', 4.0, 0.0025, 0.6)), (HALF, struct.pack('<4f', 0.5, 0.5, 0.5, 0.5)),
             (DELTAS, struct.pack('<%di' % (2 * WINDOW + 1), 0, *[s * k for k in range(1, WINDOW + 1) for s in (1, -1)])))

blocks = list(CONSTANTS)

