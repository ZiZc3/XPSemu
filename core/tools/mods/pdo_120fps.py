xf.j32(0x73, 'next')                              # jae next (past either end)
xf.raw(0x6B, 0xC0, REC)                           # imul eax, eax, REC
xf.raw(0x03, 0xC3)                                # add eax, ebx (its record)
xf.raw(0x8B, 0x4C, 0x24, STATE)                   # mov ecx, [esp+STATE]
xf.raw(0x39, 0x08)                                # cmp [eax], ecx
xf.j32(0x75, 'next')                              # jne next
xf.raw(0x39, 0x70, 0x04)                          # cmp [eax+4], esi (the same slot)
xf.j32(0x75, 'next')                              # jne next
# the translations' distance (row 3), and what it may be: NEAR + FAR * the distance from the camera
ss_mem8(xf, 'movss', 0, ESI, 0x30); ss_mem8(xf, 'subss', 0, EAX, REC_M + 0x30); xx(xf, (0xF3,), MUL, 0, 0)
ss_mem8(xf, 'movss', 2, ESI, 0x30); xx(xf, (0xF3,), MUL, 2, 2)
for k in (1, 2):
    ss_mem8(xf, 'movss', 1, ESI, 0x30 + 4 * k); ss_mem8(xf, 'subss', 1, EAX, REC_M + 0x30 + 4 * k)
    xx(xf, (0xF3,), MUL, 1, 1); xx(xf, (0xF3,), ADD, 0, 1)
    ss_mem8(xf, 'movss', 1, ESI, 0x30 + 4 * k); xx(xf, (0xF3,), MUL, 1, 1); xx(xf, (0xF3,), ADD, 2, 1)
ss_abs(xf, 'mulss', 2, FAR); ss_abs(xf, 'addss', 2, NEAR)
xf.raw(0x0F, 0x2F, 0xC2)                          # comiss xmm0, xmm2
xf.j32(0x73, 'next')                              # jae next
xf.j32(0x7A, 'next')                              # jp next
# the rotations' squares (rows 0-2)
for r in range(3):
    dst = 0 if r == 0 else 1
    xmm_mem8(xf, 'movups', dst, ESI, 16 * r); xmm_mem8(xf, 'movups', 2, EAX, REC_M + 16 * r)
    xx(xf, (), SUB, dst, 2); xx(xf, (), MUL, dst, dst)
    if r:
        xx(xf, (), ADD, 0, 1)
