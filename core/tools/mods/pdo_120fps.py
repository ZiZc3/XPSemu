"""pdo_120fps.py XBE [OUT]: Panzer Dragoon Orta's 120 fps mod
(mods/53450007.1/120fps/mod.txt) from its default.xbe: the header, then the
XBE patches, the injected code assembled here (to OUT, else stdout).

The vblank runs at 120 Hz (refresh: 120) and the game presents every vblank
(D3D's interval ONE). Its frame (0x12070) runs the logic one fixed step
(0x115B0: the controllers, the subsystems, the mode's logic from its table)
and then draws and presents (0x11B00). The code goes in the header page past
the headers (sizeof_headers 0xB20 -> 0x1000: the loader reads the page's
rest from the file, zeros there):

- A tick frame is one that finds two vblanks or more (the game's own count,
  0x4ED8F0) since the last step: it steps as before, and the step stands for
  two more vblanks (for all of them past four: a frame steps once at most,
  and a long one isn't caught up on). PARITY is 0 on tick frames.
- The other frames skip the step (the call at 0x1208D): no step, the input
  unread. The draw's frame counter (0x11B60, read as a clock by the game's
  effects) counts tick frames only.
- D3DDevice_SetTransform (0x2ADAA0) puts every frame's motion half a step
  apart: a tick frame draws each matrix halfway back to the frame before's
  (C_XFORM below says how they're matched), the other frame the step itself.
  The engine is JSRF's (tools/mods/jsrf_120fps.py): this is that mod's code
  at this game's addresses.
"""
import struct
import sys

d = open(sys.argv[1], 'rb').read()
base = struct.unpack_from('<I', d, 0x104)[0]
hdr = struct.unpack_from('<I', d, 0x108)[0]
nsec, secva = struct.unpack_from('<II', d, 0x11C)
first_raw = min(struct.unpack_from('<I', d, secva - base + i * 0x38 + 0xC)[0] for i in range(nsec))
assert hdr == 0xB20 and first_raw >= 0x1000, (hex(hdr), hex(first_raw))
assert not any(d[hdr:0x1000]), 'the header page past the headers is not empty in the file'

HEADER = """name: 120 fps
description: The game at 120 frames a second (on a 120 Hz screen), at its normal speed: it still steps 60 times a second, and every other frame shows everything halfway between two steps.
author: hakuX
refresh: 120

# The game steps its logic once a frame (0x115B0, called by the frame
# 0x12070 at 0x1208D, before it draws). With the vblank at 120 Hz the frame
# runs every vblank; one that finds two vblanks since the last step (the
# game's count 0x4ED8F0) steps, the others only draw: 60 steps a second, 120
# frames. The draw's frame counter (0x11B60) counts the stepped frames.
# Every draw's matrix (model and camera in one, from a slot of the game's
# matrix stack) goes through SetTransform (0x2ADAA0): on a stepped frame it's
# matched in the frame before's (the same slot, near the place the last
# match gave, close enough) and the mean of the two is drawn, half a step
# back. The code is in the header page (sizeof_headers raised to 0x1000),
# the records in two buffers from MmAllocateContiguousMemory. Generated by
# tools/mods/pdo_120fps.py.
[default.xbe]
"""


def file_bytes(va, n):
    """the XBE's bytes at a VA (sections' raw data, or the header page)"""
    for i in range(nsec):
        flags, sva, vsize, raw, rsize = struct.unpack_from('<IIIII', d, secva - base + i * 0x38)
        if sva <= va < sva + rsize:
            o = raw + va - sva
            return d[o:o + n]
    if base <= va < base + 0x1000:
        return d[va - base:va - base + n]
    raise ValueError(hex(va))


def hx(b):
    return ' '.join('%02X' % x for x in b)


class Asm:
    def __init__(self, at):
        self.at, self.b = at, bytearray()
        self.labels, self.fixups = {}, []

    def pc(self):
        return self.at + len(self.b)

    def raw(self, *bs):
        self.b += bytes(bs)

    def u32(self, v):
        self.b += struct.pack('<I', v & 0xFFFFFFFF)

    def rel32(self, op, target):          # E8 / E9 rel32
        self.raw(op)
        self.u32(target - (self.pc() + 4))

    def jcc32(self, op, target):          # 0F 8x rel32
        self.raw(0x0F, op)
        self.u32(target - (self.pc() + 4))

    def label(self, name):
        self.labels[name] = len(self.b)

    def j8(self, op, name):               # Jcc / JMP rel8 to a label
        self.raw(op, 0)
        self.fixups.append((len(self.b) - 1, 1, name))

    def j32(self, op, name):              # the same, rel32 (op: the rel8 form's opcode)
        self.raw(*((0xE9,) if op == 0xEB else (0x0F, op + 0x10)))
        self.u32(0)
        self.fixups.append((len(self.b) - 4, 4, name))

    def done(self):
        for at, size, name in self.fixups:
            rel = self.labels[name] - (at + size)
            if size == 1:
                assert -128 <= rel < 128, name
                self.b[at] = rel & 0xFF
            else:
                self.b[at:at + 4] = struct.pack('<i', rel)
        return self.at, bytes(self.b)


# The title's addresses
VBL = 0x4ED8F0           # the game's vblank count (its vblank callback 0x2918E0)
STEP = 0x115B0           # the logic's step, called by the frame at STEP_CALL
STEP_CALL = 0x1208D
COUNTER, COUNTED = 0x11B60, 0x11B66      # the draw's frame counter increment, and past it

SET_TRANSFORM = 0x2ADAA0     # D3DDevice_SetTransform(state, matrix): copies it into the device
ALLOC = 0x30C8B4             # the kernel thunk of MmAllocateContiguousMemory(size)

# The mod's variables and code in the header page
PARITY = 0x10B20         # 0 on tick frames
LASTTICK = 0x10B24       # the vblank count the last step stands for
INDEX = 0x10B28          # the frame's view and world matrices so far
CURBUF = 0x10B2C         # this frame's records (MAXREC: the state, the matrix's pointer, the matrix)
PREVBUF = 0x10B30        # the frame before's
PREVN = 0x10B34          # how many it has
OFF = 0x10B38            # where the frame's matrices are in the frame before's: the last match's offset
CURREC = 0x10B3C         # the record of the matrix at hand
NEAR, FAR = 0x10B40, 0x10B44   # a match's translation: within NEAR + FAR * its distance (squares)
TURN2 = 0x10B48          # its rotation: the sum of the squares it changes by within TURN2
HALF = 0x10B50           # 0.5 four times
BLEND = 0x10B60          # the matrix sent on a tick frame (64 bytes)
XMMS = 0x10BA0           # xmm0-3 kept around the search (64 bytes)
DELTAS = 0x10BE0         # the offsets tried around the last match's: 0, 1, -1 ... WINDOW, -WINDOW
