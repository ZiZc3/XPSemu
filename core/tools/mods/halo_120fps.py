"""halo_120fps.py XBE [OUT]: Halo's 120 fps mod (mods/4D530004.9/120fps/mod.txt)
from its default.xbe: the header, then the XBE patches (to OUT, else stdout).
The 60 fps mod's (halo_60fps.py, left as it is) with the vblank at 120 Hz:
the same code, whose t steps by the frames' tick fractions (a quarter tick at
120 fps), and the frame's time step taking a vblank as 1/120 s.

halo_120fps.asm (next to this script, assembled with NASM: $NASM, else nasm on
PATH) goes in the header page: over the logo bitmap (the headers' last part,
0x10A14..0x10CC6, which only the dashboard reads) and past the headers
(sizeof_headers 0xCC8 -> 0x1000: the loader reads the page's rest from the
file, zeros there).
"""
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ORG = 0x10A14

d = open(sys.argv[1], 'rb').read()
base = struct.unpack_from('<I', d, 0x104)[0]
hdr = struct.unpack_from('<I', d, 0x108)[0]
nsec, secva = struct.unpack_from('<II', d, 0x11C)
first_raw = min(struct.unpack_from('<I', d, secva - base + i * 0x38 + 0xC)[0] for i in range(nsec))
assert hdr == 0xCC8 and first_raw >= 0x1000, (hex(hdr), hex(first_raw))
assert not any(d[hdr:0x1000]), 'the header page past the headers is not empty in the file'
logo, logo_size = struct.unpack_from('<II', d, 0x170)
assert logo == ORG and logo + logo_size <= base + hdr, (hex(logo), hex(logo_size))

HEADER = """name: 120 fps
description: The game at 120 frames a second (on a 120 Hz screen) and its normal speed: characters, vehicles, objects and the first-person arms are drawn between the game's 30 updates a second (particles and effects still move 30 times a second). Use it instead of the 60 fps mod, not with it.
author: hakuX
refresh: 120

# Halo's frame limiter (0xBB5D0) waits 60 / F vblanks a frame, F being the
# video settings' frame rate (word 0x1F8C98): 0 there, the retail value,
# means 30. With 60 a frame takes one vblank, at 120 Hz. The frame's time
# step is the vblanks it took times a vblank's length (0xBB7F4: 1/60 s,
# 0x1F0CA0; now 1/120, 0x1F1194) and the game time (0xFA920) runs a tick per
# 1/30 s of it: the game keeps its speed, a tick every fourth frame.
# The frames between ticks draw what moves between the last two ticks, a
# quarter tick apart. Objects: before each tick (0xFAB11) their positions
# and node matrices are copied; after the frame's ticks (0xBD8A1) each is set
# between its two ticks for the director, the camera and the render; after
# the frame (0xBD983) its values come back. First person: the render rebuilds
# the arms each frame from the tick's pose and the camera (0xD7CC0); the pose
# of the last tick blends into it there. The code is in the header page (over
# the logo bitmap, sizeof_headers raised to 0x1000), its buffers (536 KiB)
# from MmAllocateContiguousMemory, asked for again each tick until there's
# room (a fast device's first ticks come while the game still holds its
# loading buffers). Generated by halo_120fps.py.
[default.xbe]
"""

# (VA, original bytes, new bytes or a label to call)
HOOKS = [
    (0xFAB11, 'E8 4A EC 00 00', 'pre_tick'),     # call 0x109760 (tick)
    (0xBD8A1, 'E8 7A D0 03 00', 'after_ticks'),  # call 0xFA920 (game_time_update)
    (0xBD983, 'E8 D8 D6 FF FF', 'after_frame'),  # call 0xBB060
    (0xD7CC0, 'E8 3B B9 FC FF', 'fp_pose'),      # call 0xA3600 (arms' node matrices)
]


def file_bytes(va, n):
    """the XBE's bytes at a VA (sections' raw data, or the header page)"""
    for i in range(nsec):
        flags, sva, vsize, raw, rsize = struct.unpack_from('<IIIII', d, secva - base + i * 0x38)
        if sva <= va < sva + rsize:
            o = raw + va - sva
            return d[o:o + n]
    if base <= va < base + 0x1000:
        return d[va - base:va - base + n]
    raise ValueError(hex(va))


def hx(b):
    return ' '.join('%02X' % x for x in b)


def assemble():
    """the code at ORG and its labels' addresses (NASM's symbol map)"""
    nasm = os.environ.get('NASM', 'nasm')
    with open(os.path.join(HERE, 'halo_120fps.asm')) as f:
        text = f.read()
    with tempfile.TemporaryDirectory() as t:
        src, out, mp = (os.path.join(t, n) for n in ('code.asm', 'code.bin', 'code.map'))
        with open(src, 'w') as f:
            f.write(text + '\n[map symbols %s]\n' % mp.replace('\\', '/'))
        subprocess.run([nasm, '-f', 'bin', '-o', out, src], check=True)
        code = open(out, 'rb').read()
        labels = {}
        for ln in open(mp):
            p = ln.split()
            if len(p) == 3:
                try:
                    labels[p[2]] = int(p[1], 16)
                except ValueError:
                    pass
    return code, labels


def main():
    code, labels = assemble()
    assert ORG + len(code) <= base + 0x1000, 'code too large: %d bytes' % len(code)
    # the variables from buf on stay out of the patches: zeros in the file, and
    # a savestate's values (its buffer) must survive the patches applied over it
    code = code[:labels['buf'] - ORG]
    lines = []
    lines.append('0x%08X: %s -> %s' % (base + 0x108, hx(file_bytes(base + 0x108, 4)),
                                         hx(struct.pack('<I', 0x1000))))
    for i in range(0, len(code), 32):
        chunk = code[i:i + 32]
        lines.append('0x%08X: %s -> %s' % (ORG + i, hx(file_bytes(ORG + i, len(chunk))), hx(chunk)))
    for va, old, label in HOOKS:
        have = hx(file_bytes(va, 5))
        assert have == old, (hex(va), have, old)
        target = labels[label]
        lines.append('0x%08X: %s -> %s' % (va, old, hx(b'\xE8' + struct.pack('<i', target - (va + 5)))))
    old = hx(file_bytes(0xBB647, 5))
    assert old == 'B9 1E 00 00 00', old
    lines.append('0x%08X: %s -> %s' % (0xBB647, old, 'B9 3C 00 00 00'))
    # the frame's time step: the vblanks times 1/120 s (fmul [0x1F1194], a 1/120 in .rdata)
    old = hx(file_bytes(0xBB7F4, 6))
    assert old == 'D8 0D A0 0C 1F 00' and file_bytes(0x1F1194, 4) == struct.pack('<f', 1 / 120), old
    lines.append('0x%08X: %s -> %s' % (0xBB7F6, 'A0 0C 1F 00', hx(struct.pack('<I', 0x1F1194))))
    text = HEADER + '\n'.join(lines) + '\n'
    if len(sys.argv) > 2:
        with open(sys.argv[2], 'w', newline='\n') as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    sys.stderr.write('code %d bytes at 0x%X..0x%X; %s\n' % (
        len(code), ORG, ORG + len(code), ', '.join('%s 0x%X' % (k, labels[k]) for k in
                                                   ('pre_tick', 'after_ticks', 'after_frame', 'buf'))))


if __name__ == '__main__':
    main()
